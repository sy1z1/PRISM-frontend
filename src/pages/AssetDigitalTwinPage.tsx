const PanoramaViewer = forwardRef<PanoramaViewerHandle, PanoramaViewerProps>(function PanoramaViewer({
  imageUrl,
  hotspots,
  tool,
  busy,
  onHotspotClick,
  onPlaceHotspot,
}, ref) {
  const containerRef = useRef<HTMLDivElement | null>(null);
  const pointerOrigin = useRef<{ pointerId: number; x: number; y: number; yaw: number; pitch: number } | null>(null);
  const dragged = useRef(false);
  const [camera, setCamera] = useState({ yaw: 0, pitch: 0, zoom: 1 });
  const [viewSize, setViewSize] = useState({ width: 0, height: 0 });
  const [imageFailed, setImageFailed] = useState(false);
  const [isDragging, setIsDragging] = useState(false);
  const panoramaWidth = viewSize.width * 4 * camera.zoom;
  const panoramaHeight = panoramaWidth / 2;
  const horizontalFov = 90 / camera.zoom;
  const verticalFov = viewSize.width ? horizontalFov * viewSize.height / viewSize.width : 0;
  const imageLeft = viewSize.width / 2 - panoramaWidth * (0.5 + camera.yaw / 360);
  const imageTop = viewSize.height / 2 - panoramaHeight * (0.5 - camera.pitch / 180);

  useEffect(() => {
    const node = containerRef.current;
    if (!node) return undefined;
    const observer = new ResizeObserver((entries) => {
      const bounds = entries[0]?.contentRect;
      if (bounds) setViewSize({ width: bounds.width, height: bounds.height });
    });
    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  useImperativeHandle(ref, () => ({
    captureView: async () => {
      const node = containerRef.current;
      if (!node || imageFailed) throw new Error('The panorama image is unavailable for screenshot capture.');

      const bounds = node.getBoundingClientRect();
      if (!bounds.width || !bounds.height) throw new Error('The 360° viewer has no visible area to capture.');

      const images = Array.from(node.querySelectorAll('img'));
      const visibleImages = images.filter((image) => {
        const rect = image.getBoundingClientRect();
        return rect.right > bounds.left && rect.left < bounds.right && rect.bottom > bounds.top && rect.top < bounds.bottom;
      });
      if (!visibleImages.length) throw new Error('The panorama has not finished rendering. Please try again.');

      const waitForImage = (image: HTMLImageElement) => new Promise<void>((resolve, reject) => {
        if (image.complete) {
          if (image.naturalWidth > 0) resolve();
          else reject(new Error('The panorama image failed to load.'));
          return;
        }

        const timeout = window.setTimeout(() => finish(new Error('The panorama is still loading. Please try again.')), 10000);
        const cleanup = () => {
          window.clearTimeout(timeout);
          image.removeEventListener('load', onLoad);
          image.removeEventListener('error', onError);
        };
        const finish = (error?: Error) => {
          cleanup();
          if (error) reject(error);
          else resolve();
        };
        const onLoad = () => finish(image.naturalWidth > 0 ? undefined : new Error('The panorama image failed to load.'));
        const onError = () => finish(new Error('The panorama image failed to load.'));
        image.addEventListener('load', onLoad, { once: true });
        image.addEventListener('error', onError, { once: true });
      });

      await Promise.all(visibleImages.map(waitForImage));

      const pixelRatio = Math.min(window.devicePixelRatio || 1, 2, 4096 / bounds.width, 4096 / bounds.height);
      const canvas = document.createElement('canvas');
      canvas.width = Math.round(bounds.width * pixelRatio);
      canvas.height = Math.round(bounds.height * pixelRatio);
      const context = canvas.getContext('2d');
      if (!context) throw new Error('This browser cannot prepare screenshot evidence.');

      try {
        context.scale(pixelRatio, pixelRatio);
        const background = context.createLinearGradient(0, 0, 0, bounds.height);
        background.addColorStop(0, '#26343d');
        background.addColorStop(1, '#111a22');
        context.fillStyle = background;
        context.fillRect(0, 0, bounds.width, bounds.height);
        context.save();
        context.beginPath();
        context.rect(0, 0, bounds.width, bounds.height);
        context.clip();

        visibleImages.forEach((image) => {
          const rect = image.getBoundingClientRect();
          context.drawImage(image, rect.left - bounds.left, rect.top - bounds.top, rect.width, rect.height);
        });

        node.querySelectorAll<HTMLButtonElement>('.dt-hotspot-button').forEach((hotspot) => {
          const rect = hotspot.getBoundingClientRect();
          const centerX = rect.left - bounds.left + rect.width / 2;
          const centerY = rect.top - bounds.top + rect.height / 2;
          context.beginPath();
          context.arc(centerX, centerY, 13, 0, Math.PI * 2);
          context.fillStyle = 'rgba(61, 237, 155, 0.2)';
          context.fill();
          context.beginPath();
          context.arc(centerX, centerY, 8, 0, Math.PI * 2);
          context.fillStyle = '#54f0a1';
          context.fill();
          context.lineWidth = 2;
          context.strokeStyle = 'rgba(224, 255, 240, 0.9)';
          context.stroke();
        });
        context.restore();

        if (typeof canvas.toBlob !== 'function') {
          throw new Error('This browser does not support screenshot export. You can continue without optional evidence.');
        }
        const blob = await new Promise<Blob>((resolve, reject) => {
          try {
            canvas.toBlob((result) => {
              if (result) resolve(result);
              else reject(new Error('This browser or image source blocked screenshot export. You can submit without optional evidence.'));
            }, 'image/jpeg', 0.92);
          } catch (error) {
            reject(error);
          }
        });

        return { blob, yaw: camera.yaw, pitch: camera.pitch, zoom: camera.zoom, width: bounds.width, height: bounds.height };
      } catch (error) {
        if (error instanceof DOMException && error.name === 'SecurityError') {
          throw new Error('The image source blocks screenshot export because of cross-origin restrictions. You can continue without optional evidence.');
        }
        throw error;
      }
    },
  }), [camera.pitch, camera.yaw, camera.zoom, imageFailed]);

  const onPointerDown = (event: ReactPointerEvent<HTMLDivElement>) => {
    if (tool !== 'pan' || event.button !== 0) return;
    const node = event.currentTarget;
    pointerOrigin.current = {
      pointerId: event.pointerId,
      x: event.clientX,
      y: event.clientY,
      yaw: camera.yaw,
      pitch: camera.pitch,
    };
    dragged.current = false;
    setIsDragging(true);
    node.setPointerCapture(event.pointerId);
  };

  const onPointerMove = (event: ReactPointerEvent<HTMLDivElement>) => {
    const origin = pointerOrigin.current;
    if (!origin || origin.pointerId !== event.pointerId || !viewSize.width || !viewSize.height) return;
    const deltaX = event.clientX - origin.x;
    const deltaY = event.clientY - origin.y;
    if (Math.abs(deltaX) + Math.abs(deltaY) > 3) dragged.current = true;
    const fov = 90 / camera.zoom;
    const pitchFov = fov * viewSize.height / viewSize.width;
    setCamera((current) => ({
      ...current,
      yaw: normalizeYaw(origin.yaw - deltaX * fov / viewSize.width),
      pitch: Math.max(-80, Math.min(80, origin.pitch + deltaY * pitchFov / viewSize.height)),
    }));
  };

  const onPointerUp = (event: ReactPointerEvent<HTMLDivElement>) => {
    if (pointerOrigin.current?.pointerId === event.pointerId) {
      pointerOrigin.current = null;
      setIsDragging(false);
    }
  };

  const onViewerClick = (event: ReactMouseEvent<HTMLDivElement>) => {
    if (tool !== 'place' || dragged.current || !viewSize.width || !viewSize.height) {
      dragged.current = false;
      return;
    }
    const bounds = event.currentTarget.getBoundingClientRect();
    const x = event.clientX - bounds.left;
    const y = event.clientY - bounds.top;
    const yaw = normalizeYaw(camera.yaw + (x / viewSize.width - 0.5) * horizontalFov);
    const pitch = Math.max(-90, Math.min(90, camera.pitch - (y / viewSize.height - 0.5) * verticalFov));
    onPlaceHotspot({ yaw, pitch });
  };

  const onWheel = (event: ReactWheelEvent<HTMLDivElement>) => {
    setCamera((current) => ({ ...current, zoom: Math.max(0.7, Math.min(2.8, current.zoom + (event.deltaY < 0 ? 0.12 : -0.12))) }));
  };

  const handleFullscreen = () => {
    const node = containerRef.current;
    if (!node) return;
    if (document.fullscreenElement) void document.exitFullscreen();
    else void node.requestFullscreen();
  };

  return (
    <div
      ref={containerRef}
      style={{ ...styles.panorama, cursor: tool === 'place' ? 'crosshair' : isDragging ? 'grabbing' : 'grab' }}
      onPointerDown={onPointerDown}
      onPointerMove={onPointerMove}
      onPointerUp={onPointerUp}
      onPointerCancel={onPointerUp}
      onClick={onViewerClick}
      onWheel={onWheel}
      role="application"
      aria-label="Interactive 360 degree asset panorama. Drag to look around and use the scroll wheel to zoom."
    >
      {!imageFailed ? [-1, 0, 1].map((copy) => (
        <img
          key={copy}
          src={imageUrl}
          alt=""
          draggable={false}
          onError={() => setImageFailed(true)}
          style={{ ...styles.panoramaImage, width: panoramaWidth, height: panoramaHeight, left: imageLeft + copy * panoramaWidth, top: imageTop }}
        />
      )) : (
        <div style={styles.panoramaError}>
          <Camera size={32} />
          <span>Unable to load this 360° image.</span>
        </div>
      )}

      {!imageFailed && viewSize.width > 0 && hotspots.map((hotspot) => {
        const deltaYaw = normalizeYaw(hotspot.yaw - camera.yaw);
        const deltaPitch = hotspot.pitch - camera.pitch;
        const left = viewSize.width / 2 + deltaYaw / horizontalFov * viewSize.width;
        const top = viewSize.height / 2 - (verticalFov ? deltaPitch / verticalFov * viewSize.height : 0);
        if (Math.abs(deltaYaw) > horizontalFov * 0.58 || Math.abs(deltaPitch) > verticalFov * 0.58) return null;
        return (
          <button
            key={hotspot.id}
            type="button"
            className="dt-hotspot-button"
            onPointerDown={(event) => event.stopPropagation()}
            onClick={(event) => { event.stopPropagation(); onHotspotClick(hotspot.targetAssetId); }}
            style={{ ...styles.hotspotButton, left, top }}
            title={`Open ${hotspot.targetAssetName}`}
            aria-label={`Open linked asset ${hotspot.targetAssetName}`}
          >
            <span style={styles.hotspotPulse} />
            <span style={styles.hotspotDot} />
            <span style={styles.hotspotLabel}>{hotspot.targetAssetName}</span>
          </button>
        );
      })}

      <div style={styles.viewerCompass}>
        <Crosshair size={14} />
        <span>{Math.round(camera.yaw)}°</span>
        <span style={styles.compassDivider} />
        <span>{Math.round(camera.pitch)}°</span>
      </div>

      <div style={styles.zoomControls} onPointerDown={(event) => event.stopPropagation()}>
        <button type="button" className="dt-zoom-button" style={styles.zoomButton} onClick={() => setCamera((current) => ({ ...current, zoom: Math.min(2.8, current.zoom + 0.15) }))} aria-label="Zoom in"><Plus size={17} /></button>
        <span style={styles.zoomRule} />
        <button type="button" className="dt-zoom-button" style={styles.zoomButton} onClick={() => setCamera((current) => ({ ...current, zoom: Math.max(0.7, current.zoom - 0.15) }))} aria-label="Zoom out"><Minus size={17} /></button>
        <span style={styles.zoomRule} />
        <button type="button" className="dt-zoom-button" style={styles.zoomButton} onClick={() => setCamera({ yaw: 0, pitch: 0, zoom: 1 })} aria-label="Reset panorama view" title="Reset view"><RotateCcw size={15} /></button>
        <button type="button" className="dt-zoom-button" style={styles.fullscreenButton} onClick={handleFullscreen} aria-label="Toggle fullscreen" title="Fullscreen"><Expand size={15} /></button>
      </div>

      {busy && <div style={styles.panoramaBusy}><LoaderCircle size={16} style={{ animation: 'digital-twin-spin 1s linear infinite' }} /> Saving hotspot</div>}
    </div>
  );
});

